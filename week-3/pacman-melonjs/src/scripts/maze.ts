export const ROWS = MAZE.length;
export const COLS = MAZE[0].length;

export function isWall(column: number, row: number): boolean {
    if (column < 0 || column >= COLS || row < 0 || row >= ROWS) {
        return true;
    }

    return MAZE[row][column] === 1;
}

export function hasRemainingDots(): boolean {
    for (let row = 0; row < ROWS; row++) {
        for (let column = 0; column < COLS; column++) {
            if (MAZE[row][column] === 0) {
                return true;
            }
        }
    }

    return false;
}